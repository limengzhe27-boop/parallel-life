const beginBody = z.strictObject({
  mimeType: z.enum(['image/jpeg', 'image/png', 'image/webp', 'video/mp4']),
  byteLength: z.number().int().min(1).max(50_000_000),
});

let publisherDb: PostgresDatabase | undefined;
let publisherDatabaseUrl: string | undefined;

export function getPublicationMediaStore(): PublicationMediaStore {
  const url = process.env.SUPABASE_URL;
  const serviceRoleKey = process.env.SUPABASE_SECRET_KEY ?? process.env.SUPABASE_SERVICE_ROLE_KEY;
  const remote =
    url && serviceRoleKey ? new SupabasePublicationMediaStore({ url, serviceRoleKey }) : undefined;
  if (
    publicationLocalStorageEnabled({
      vercel: process.env.VERCEL,
      origin: process.env.APP_ORIGIN,
      directory: process.env.PRIVATE_ASSET_DIR,
    })
  )
    return new LocalFirstPublicationMediaStore(
      path.join(process.env.PRIVATE_ASSET_DIR!, 'publication-media'),
      remote,
    );
  if (!remote) throw new PublisherHttpError('UNAVAILABLE');
  return remote;
}

export function getPublicationMediaRepository() {
  if (isPreviewOnly()) throw new PublisherHttpError('UNAVAILABLE');
  const url = process.env.PUBLISHER_DATABASE_URL;
  if (!url) throw new PublisherHttpError('UNAVAILABLE');
  const parsed = new URL(url);
  if (
    !['postgres:', 'postgresql:'].includes(parsed.protocol) ||
    decodeURIComponent(parsed.username).split('.')[0] !== 'pl_publisher_login' ||
    (publisherDatabaseUrl && publisherDatabaseUrl !== url)
  ) {
    throw new PublisherHttpError('UNAVAILABLE');
  }
  publisherDb ??= new PostgresDatabase(url);
  publisherDatabaseUrl = url;
  return new PublicationMediaRepository(publisherDb, getPublicationMediaStore());
}

function mediaRedirect(location: string) {
  return new Response(null, {
    status: 302,
    headers: {
      Location: location,
      'Cache-Control': 'private, no-store',
      'Referrer-Policy': 'no-referrer',
      'X-Content-Type-Options': 'nosniff',
    },
  });
}

/** The caller must first authorize this exact row with publisherAsset/playerAsset. */
export async function readStoredAsset(asset: {
  storage_key: string;
  mime_type: string;
  byte_length: string | number;
}) {
  const store = getPublicationMediaStore();
  const bytes = await store.readStored?.(asset.storage_key);
  if (bytes) {
    if (bytes.length !== Number(asset.byte_length)) throw new PublisherHttpError('UNAVAILABLE');
    return new Response(new Uint8Array(bytes), {
      headers: {
        'Content-Type': asset.mime_type,
        'Content-Length': String(bytes.length),
        'Cache-Control': 'private, no-store',
        'X-Content-Type-Options': 'nosniff',
        'Referrer-Policy': 'no-referrer',
      },
    });
  }
  return mediaRedirect(await store.signRead(asset.storage_key));
}

/** Server-generated bytes use the same pending row, validation and finalization as uploads. */
export async function putGeneratedPublicationMedia(
  principalId: string,
  workId: string,
  assetId: string,
  bytes: Buffer,
  mimeType: PublicationMediaMime,
) {
  const repo = getPublicationMediaRepository();
  const admitted = await repo.beginGenerated(principalId, workId, assetId, bytes.length, mimeType);
  // A ready asset is immutable: replay returns it without overwriting bytes.
  if (admitted.status === 'ready') return repo.finalize(principalId, workId, assetId);
  const row = await repo.pendingAsset(principalId, workId, assetId);
  await putPendingBytes(row, bytes, mimeType);
  return repo.finalize(principalId, workId, assetId);
}
async function putPendingBytes(
  row: { storage_key: string; mime_type: PublicationMediaMime; declared_bytes: string | number },
  bytes: Buffer,
  mimeType: string,
) {
  if (
    row.mime_type !== mimeType ||
    Number(row.declared_bytes) !== bytes.length ||
    !publicationMediaMagic(row.mime_type, bytes.subarray(0, 4096))
  )
    throw new PublisherHttpError('INVALID_INPUT');
  const store = getPublicationMediaStore();
  if (!store.put) throw new PublisherHttpError('UNAVAILABLE');
  await store.put(row.storage_key, bytes);
}
export function publisherMediaContentRoute(request: Request, workId: string, assetId: string) {
  return publisherEndpoint(async () => {
    const principal = await publisherServices(request).http.authorize(request, true, 'edit');
    const store = getPublicationMediaStore();
    if (!store.put) throw new PublisherHttpError('NOT_FOUND');
    const row = await getPublicationMediaRepository().pendingAsset(principal.id, workId, assetId);
    const mimeType = request.headers.get('content-type')?.split(';')[0]?.trim() ?? '';
    const expected = Number(row.declared_bytes);
    if (mimeType !== row.mime_type || expected < 1 || expected > 50_000_000)
      throw new PublisherHttpError('INVALID_INPUT');
    const declared = request.headers.get('content-length');
    if (declared !== null && Number(declared) !== expected)
      throw new PublisherHttpError('INVALID_INPUT');
    const reader = request.body?.getReader();
    if (!reader) throw new PublisherHttpError('INVALID_INPUT');
    const chunks: Uint8Array[] = [];
    let size = 0;
    try {
      while (true) {
        const { value, done } = await reader.read();
        if (done) break;
        size += value.length;
        if (size > expected) throw new PublisherHttpError('CONTENT_TOO_LARGE');
        chunks.push(value);
      }
    } finally {
      await reader.cancel().catch(() => {});
    }
    await putPendingBytes(row, Buffer.concat(chunks), mimeType);
    return publisherJson({ assetId }, 201);
  });
}

/** Caller has already authenticated the staff principal and resolved this exact trial binding. */
export async function readTrialPublicationMedia(ownerId: string, worldId: string, assetId: string) {
  const repo = new PublicationMediaRepository(getServices().db, getPublicationMediaStore());
  const asset = await repo.playerAsset(ownerId, worldId, assetId);
  return readStoredAsset(asset);
}

export function publisherMediaBeginRoute(request: Request, workId: string) {
  return publisherEndpoint(async () => {
    const services = publisherServices(request);
    const principal = await services.http.authorize(request, true, 'edit');
    const input = await publisherBody(request, beginBody);
    const result = await getPublicationMediaRepository().begin(principal.id, workId, input);
    return publisherJson(result, 201);
  });
}

export function publisherMediaFinalizeRoute(request: Request, workId: string, assetId: string) {
  return publisherEndpoint(async () => {
    const services = publisherServices(request);
    const principal = await services.http.authorize(request, true, 'edit');
    // The empty body is intentional: bytes never travel through this route.
    const result = await getPublicationMediaRepository().finalize(principal.id, workId, assetId);
    return publisherJson(result);
  });
}

export function publisherMediaReadRoute(request: Request, workId: string, assetId: string) {
  return publisherEndpoint(async () => {
    const services = publisherServices(request);
    const principal = await services.http.authorize(request, false, 'review');
    const repo = getPublicationMediaRepository();
    const asset = await repo.publisherAsset(principal.id, workId, assetId);
    return readStoredAsset(asset);
  });
}

export function playerPublicationMediaReadRoute(
  request: Request,
  worldId: string,
  assetId: string,
) {
  return endpoint(async () => {
    const services = await authenticated(request);
    const repo = new PublicationMediaRepository(services.db, getPublicationMediaStore());
    const asset = await repo.playerAsset(services.ownerId, worldId, assetId);
    return readStoredAsset(asset);
  });
}
